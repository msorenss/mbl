#[tokio::test]
async fn m9_mcp_livetv_tools() {
    let (app, _db, _services) = TestApp::new_with_services().await;
    let admin_session = app.setup_admin().await;

    let tok_res = app
        .call(
            Method::POST,
            "/api/v1/auth/tokens",
            Some(&admin_session),
            Some(json!({
                "name": "livetv-bot",
                "scopes": ["admin"]
            })),
        )
        .await;
    assert_eq!(tok_res.status, StatusCode::CREATED);
    let token = tok_res.body["token"].as_str().unwrap().to_owned();

    let mut client = McpClient::connect_router(app.router.clone(), Some(token));
    let _init = client.initialize().await.unwrap();

    // 1. Setup sample channel and guide data via REST
    let m3u =
        "#EXTM3U\n#EXTINF:-1 tvg-id=\"svt1.se\",SVT 1 HD\nhttps://live.example.com/svt1.m3u8\n";
    app.call(
        Method::POST,
        "/api/v1/livetv/tuners/m3u",
        Some(&admin_session),
        Some(json!({ "name": "SVT", "content": m3u })),
    )
    .await;

    let xmltv = r#"<?xml version="1.0" encoding="UTF-8"?>
<tv>
  <programme channel="svt1.se" start="20261026190000 +0000" stop="20261026200000 +0000">
    <title lang="sv">Bäst i test</title>
    <desc lang="sv">Underhållningsprogram</desc>
  </programme>
</tv>"#;

    let req = Request::builder()
        .method(Method::POST)
        .uri("/api/v1/livetv/epg/xmltv")
        .header(header::AUTHORIZATION, format!("Bearer {admin_session}"))
        .header(header::CONTENT_TYPE, "application/xml")
        .body(Body::from(xmltv))
        .unwrap();
    app.send(req).await;

    // 2. Tool: search_guide
    let search_res =
        client.call_tool("search_guide", json!({ "query": "Bäst i test" })).await.unwrap();
    assert!(!search_res.is_error);
    let progs = search_res.structured_content.as_ref().unwrap().as_array().unwrap();
    assert_eq!(progs.len(), 1);
    assert_eq!(progs[0]["title"].as_str().unwrap(), "Bäst i test");

    // 3. Tool: schedule_recording with dry_run
    let dry_rec = client
        .call_tool(
            "schedule_recording",
            json!({
                "channel_id": 1,
                "title": "Bäst i test",
                "start_time": 1793041200,
                "end_time": 1793044800,
                "dry_run": true
            }),
        )
        .await
        .unwrap();
    assert!(!dry_rec.is_error);
    assert_eq!(dry_rec.structured_content.as_ref().unwrap()["dryRun"], true);

    // Live schedule recording
    let live_rec = client
        .call_tool(
            "schedule_recording",
            json!({
                "channel_id": 1,
                "title": "Bäst i test",
                "start_time": 1793041200,
                "end_time": 1793044800,
                "dry_run": false,
                "confirm": true
            }),
        )
        .await
        .unwrap();
    assert!(!live_rec.is_error);
    let rec_id = live_rec.structured_content.as_ref().unwrap()["id"].as_i64().unwrap();

    // 4. Tool: list_recordings
    let list_tool =
        client.call_tool("list_recordings", json!({ "status": "scheduled" })).await.unwrap();
    assert!(!list_tool.is_error);
    let recs = list_tool.structured_content.as_ref().unwrap().as_array().unwrap();
    assert_eq!(recs.len(), 1);

    // 5. Tool: create_series_rule
    let rule_tool = client
        .call_tool(
            "create_series_rule",
            json!({
                "title": "Bäst i test",
                "channel_id": 1,
                "new_only": true,
                "dry_run": false,
                "confirm": true
            }),
        )
        .await
        .unwrap();
    assert!(!rule_tool.is_error);
    let rule_id = rule_tool.structured_content.as_ref().unwrap()["id"].as_i64().unwrap();
    assert!(rule_id > 0);

    // 6. Tool: cancel_recording
    let cancel_tool = client
        .call_tool(
            "cancel_recording",
            json!({
                "recording_id": rec_id,
                "confirm": true
            }),
        )
        .await
        .unwrap();
    assert!(!cancel_tool.is_error);
    assert_eq!(cancel_tool.structured_content.as_ref().unwrap()["cancelled"], true);
}
