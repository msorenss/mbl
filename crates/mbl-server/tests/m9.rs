#[tokio::test]
async fn m9_virtual_channels_and_zero_cpu_playhead() {
    let (app, db, _services) = TestApp::new_with_services().await;
    let admin_token = app.setup_admin().await;

    // 1. Create a library item for virtual channel playback
    let media_dir = app.media_dir("VirtualMedia");
    let lib_res = app
        .call(
            Method::POST,
            "/api/v1/libraries",
            Some(&admin_token),
            Some(json!({ "name": "VirtualMedia", "kind": "movie", "paths": [media_dir] })),
        )
        .await;
    let lib_id = lib_res.body["id"].as_i64().unwrap();

    let item_id: i64 = sqlx::query_scalar(
        "INSERT INTO media_items (library_id, kind, title, sort_title, added_at, updated_at)
         VALUES (?, 'movie', 'Star Wars Classic', 'star wars classic', 100, 100) RETURNING id",
    )
    .bind(lib_id)
    .fetch_one(&db.write)
    .await
    .unwrap();

    let ver_id: i64 = sqlx::query_scalar(
        "INSERT INTO media_versions (item_id, container, video_codec, audio_codec, width, height)
         VALUES (?, 'mp4', 'h264', 'aac', 1920, 1080) RETURNING id",
    )
    .bind(item_id)
    .fetch_one(&db.write)
    .await
    .unwrap();

    let _part_id: i64 = sqlx::query_scalar(
        "INSERT INTO media_parts (version_id, path, size, mtime, duration_ms, part_index, probe)
         VALUES (?, '/media/starwars.mp4', 1024, 1, 7200000, 0, '{}') RETURNING id",
    )
    .bind(ver_id)
    .fetch_one(&db.write)
    .await
    .unwrap();

    // 2. Create Virtual 24/7 Channel
    let vc_res = app
        .call(
            Method::POST,
            "/api/v1/livetv/virtual-channels",
            Some(&admin_token),
            Some(json!({
                "name": "Sci-Fi 24/7",
                "channelNumber": "200",
                "mode": "linear_loop",
                "itemIds": [item_id],
                "insertCommercials": false
            })),
        )
        .await;
    assert_eq!(vc_res.status, StatusCode::OK);
    let vc_id = vc_res.body["id"].as_i64().unwrap();
    assert_eq!(vc_res.body["name"].as_str().unwrap(), "Sci-Fi 24/7");

    // 3. Calculate mathematical zero-CPU playhead
    let playhead_res = app
        .call(
            Method::GET,
            &format!("/api/v1/livetv/virtual-channels/{vc_id}/playhead"),
            Some(&admin_token),
            None,
        )
        .await;
    assert_eq!(playhead_res.status, StatusCode::OK);
    assert_eq!(playhead_res.body["channelName"].as_str().unwrap(), "Sci-Fi 24/7");
    assert_eq!(playhead_res.body["currentTitle"].as_str().unwrap(), "Star Wars Classic");
    assert_eq!(playhead_res.body["durationSecs"].as_f64().unwrap(), 7200.0);
    let offset = playhead_res.body["offsetSecs"].as_f64().unwrap();
    assert!((0.0..7200.0).contains(&offset));

    // 4. Delete virtual channel
    let del_vc = app
        .call(
            Method::DELETE,
            &format!("/api/v1/livetv/virtual-channels/{vc_id}"),
            Some(&admin_token),
            None,
        )
        .await;
    assert_eq!(del_vc.status, StatusCode::OK);
    assert!(del_vc.body["success"].as_bool().unwrap());
}

