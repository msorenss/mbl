#[tokio::test]
async fn m9_tuner_and_m3u_channel_management() {
    let (app, _db, _services) = TestApp::new_with_services().await;
    let admin_token = app.setup_admin().await;

    // 1. Discover HDHomeRun tuners on LAN
    let disc_res =
        app.call(Method::POST, "/api/v1/livetv/tuners/discover", Some(&admin_token), None).await;
    assert_eq!(disc_res.status, StatusCode::OK);
    assert!(disc_res.body.is_array());

    // 2. Import M3U IPTV playlist
    let m3u_content = r#"#EXTM3U
#EXTINF:-1 tvg-id="svt1.se" tvg-name="SVT 1 HD" tvg-logo="https://example.com/svt1.png",SVT 1 HD
https://live.example.com/svt1/index.m3u8
#EXTINF:-1 tvg-id="svt2.se" tvg-name="SVT 2 HD" tvg-logo="https://example.com/svt2.png",SVT 2 HD
https://live.example.com/svt2/index.m3u8
"#;

    let import_res = app
        .call(
            Method::POST,
            "/api/v1/livetv/tuners/m3u",
            Some(&admin_token),
            Some(json!({
                "name": "Nordic Public TV",
                "content": m3u_content
            })),
        )
        .await;
    assert_eq!(import_res.status, StatusCode::OK);
    let tuner_id = import_res.body["id"].as_i64().unwrap();
    assert_eq!(import_res.body["name"].as_str().unwrap(), "Nordic Public TV");
    assert_eq!(import_res.body["kind"].as_str().unwrap(), "m3u");

    // 3. List tuners
    let tuners_res = app.call(Method::GET, "/api/v1/livetv/tuners", Some(&admin_token), None).await;
    assert_eq!(tuners_res.status, StatusCode::OK);
    assert_eq!(tuners_res.body.as_array().unwrap().len(), 1);

    // 4. List channels generated by M3U import
    let chan_res = app.call(Method::GET, "/api/v1/livetv/channels", Some(&admin_token), None).await;
    assert_eq!(chan_res.status, StatusCode::OK);
    let channels = chan_res.body.as_array().unwrap();
    assert_eq!(channels.len(), 2);
    let ch1 = &channels[0];
    assert_eq!(ch1["name"].as_str().unwrap(), "SVT 1 HD");
    assert_eq!(ch1["epgChannelId"].as_str().unwrap(), "svt1.se");
    let ch1_id = ch1["id"].as_i64().unwrap();

    // 5. Update channel (favorite toggle and custom number)
    let patch_res = app
        .call(
            Method::PATCH,
            &format!("/api/v1/livetv/channels/{ch1_id}"),
            Some(&admin_token),
            Some(json!({
                "channelNumber": "101",
                "isFavorite": true
            })),
        )
        .await;
    assert_eq!(patch_res.status, StatusCode::OK);
    assert_eq!(patch_res.body["channelNumber"].as_str().unwrap(), "101");
    assert!(patch_res.body["isFavorite"].as_bool().unwrap());

    // 6. Delete tuner
    let del_res = app
        .call(
            Method::DELETE,
            &format!("/api/v1/livetv/tuners/{tuner_id}"),
            Some(&admin_token),
            None,
        )
        .await;
    assert_eq!(del_res.status, StatusCode::OK);
    assert!(del_res.body["success"].as_bool().unwrap());

    // Channels associated with deleted tuner are purged
    let chan_after =
        app.call(Method::GET, "/api/v1/livetv/channels", Some(&admin_token), None).await;
    assert_eq!(chan_after.status, StatusCode::OK);
    assert_eq!(chan_after.body.as_array().unwrap().len(), 0);
}

#[tokio::test]
async fn m9_xmltv_streaming_guide_and_epg_grid() {
    let (app, _db, _services) = TestApp::new_with_services().await;
    let admin_token = app.setup_admin().await;

    // 1. Setup channel via M3U
    let m3u =
        "#EXTM3U\n#EXTINF:-1 tvg-id=\"svt1.se\",SVT 1 HD\nhttps://live.example.com/svt1.m3u8\n";
    app.call(
        Method::POST,
        "/api/v1/livetv/tuners/m3u",
        Some(&admin_token),
        Some(json!({ "name": "SVT", "content": m3u })),
    )
    .await;

    // 2. Streamingly import XMLTV guide via POST raw XML
    let xmltv_data = r#"<?xml version="1.0" encoding="UTF-8"?>
<tv>
  <channel id="svt1.se">
    <display-name>SVT 1</display-name>
  </channel>
  <programme channel="svt1.se" start="20261026190000 +0000" stop="20261026193000 +0000">
    <title lang="sv">Rapport</title>
    <desc lang="sv">Sveriges mest sedda nyhetsprogram.</desc>
    <category>Nyheter</category>
    <rating system="SE"><value>Alla</value></rating>
  </programme>
  <programme channel="svt1.se" start="20261026193000 +0000" stop="20261026203000 +0000">
    <title lang="sv">Aktuellt</title>
    <desc lang="sv">Fördjupande nyheter och debatt.</desc>
    <category>Nyheter</category>
  </programme>
</tv>"#;

    let req = Request::builder()
        .method(Method::POST)
        .uri("/api/v1/livetv/epg/xmltv")
        .header(header::AUTHORIZATION, format!("Bearer {admin_token}"))
        .header(header::CONTENT_TYPE, "application/xml")
        .body(Body::from(xmltv_data))
        .unwrap();

    let xml_res = app.send(req).await;
    assert_eq!(xml_res.status, StatusCode::OK);
    assert_eq!(xml_res.body["count"].as_u64().unwrap(), 2);

    // 3. Query 2-axis EPG Grid
    // 2026-10-26 19:00:00 UTC = 1793041200
    let start_ts = 1793041200i64;
    let end_ts = start_ts + 7200; // 2 hour window

    let grid_res = app
        .call(
            Method::GET,
            &format!(
                "/api/v1/livetv/epg?startTime={start_ts}&endTime={end_ts}&includeHidden=false"
            ),
            Some(&admin_token),
            None,
        )
        .await;
    assert_eq!(grid_res.status, StatusCode::OK);
    assert_eq!(grid_res.body["startTime"].as_i64().unwrap(), start_ts);
    assert_eq!(grid_res.body["endTime"].as_i64().unwrap(), end_ts);

    let grid_channels = grid_res.body["channels"].as_array().unwrap();
    assert_eq!(grid_channels.len(), 1);
    let chan_grid = &grid_channels[0];
    assert_eq!(chan_grid["channel"]["name"].as_str().unwrap(), "SVT 1 HD");
    let progs = chan_grid["programs"].as_array().unwrap();
    assert_eq!(progs.len(), 2);
    assert_eq!(progs[0]["title"].as_str().unwrap(), "Rapport");
    assert_eq!(progs[1]["title"].as_str().unwrap(), "Aktuellt");

    // 4. Guide Search
    let search_res = app
        .call(Method::GET, "/api/v1/livetv/epg/search?query=Aktuellt", Some(&admin_token), None)
        .await;
    assert_eq!(search_res.status, StatusCode::OK);
    let search_items = search_res.body.as_array().unwrap();
    assert_eq!(search_items.len(), 1);
    assert_eq!(search_items[0]["title"].as_str().unwrap(), "Aktuellt");
}

