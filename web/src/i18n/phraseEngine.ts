function lookupDirectOrExact(
  phrase: string,
  loc: AppLocale,
  idx: number,
  primaryLookup: (p: string, l: AppLocale) => string | undefined,
): string | undefined {
  const p1 = primaryLookup(phrase, loc);
  if (p1) return p1;
  const normEllipsis = phrase.replace(/\.{3}/g, "…");
  if (normEllipsis !== phrase) {
    const p2 = primaryLookup(normEllipsis, loc);
    if (p2) return p2;
  }
  const normDots = phrase.replace(/…/g, "...");
  if (normDots !== phrase) {
    const p3 = primaryLookup(normDots, loc);
    if (p3) return p3;
  }
  const row =
    EXACT_MAP.get(phrase) ||
    EXACT_MAP.get(phrase.toLowerCase()) ||
    EXACT_MAP.get(normEllipsis) ||
    EXACT_MAP.get(normEllipsis.toLowerCase());
  return row ? row[idx] : undefined;
}

export function lookupExtendedPhrase(
  input: string,
  loc: AppLocale,
  primaryLookup: (phrase: string, loc: AppLocale) => string | undefined,
): string | undefined {
  if (loc === "en") return undefined;
  const idx = LOCALE_INDEX.get(loc);
  if (idx === undefined) return undefined;

  const trimmed = input.trim().replace(/’/g, "'");
  if (!trimmed) return undefined;

  // 1. Direct lookup in primary dictionary or EXACT_MAP
  const direct = lookupDirectOrExact(trimmed, loc, idx, primaryLookup);
  if (direct) return direct;

  // 2. "e.g. <rest>" placeholder prefix
  const egMatch = trimmed.match(/^e\.g\.\s+(.+)$/i);
  if (egMatch) {
    const rest = egMatch[1].trim();
    const translatedRest = lookupExtendedPhrase(rest, loc, primaryLookup) ?? rest;
    return `${FOR_EXAMPLE_PREFIX_22[idx]} ${translatedRest}`;
  }

  // 3. Parenthetical decomposition: "Main Text (Sub Text)" when balanced
  const parenMatch = trimmed.match(/^(.+?)\s*\(([^()]+)\)$/);
  if (parenMatch) {
    const mainPart = parenMatch[1].trim();
    const subPart = parenMatch[2].trim();
    const tMain = lookupExtendedPhrase(mainPart, loc, primaryLookup);
    const tSub = lookupExtendedPhrase(subPart, loc, primaryLookup);
    if (tMain || tSub) {
      return `${tMain ?? mainPart} (${tSub ?? subPart})`;
    }
  }

  // 4. Strip leading emojis/arrows/symbols/numbers and trailing colons/brackets/quotes/ellipses
  const leadMatch = trimmed.match(LEADING_DECORATION_RE);
  const lead = leadMatch ? leadMatch[1] : "";
  const restAfterLead = trimmed.slice(lead.length);
  const trailMatch = restAfterLead.match(TRAILING_DECORATION_RE);
  const trail = trailMatch ? trailMatch[1] : "";
  const core = restAfterLead.slice(0, restAfterLead.length - trail.length).trim();

  if (core && core !== trimmed) {
    const directCore = lookupDirectOrExact(core, loc, idx, primaryLookup);
    if (directCore !== undefined) {
      return `${lead}${directCore}${trail}`;
    }
    const coreHit = lookupExtendedPhrase(core, loc, primaryLookup);
    if (coreHit !== undefined) {
      return `${lead}${coreHit}${trail}`;
    }
  }

  // 5. Compound strings separated by " — ", " · ", " • ", ": ", "; ", " / ", " & ", or ". "
  for (const sep of [" — ", " · ", " • ", ": ", "; ", " / ", " & ", ". "]) {
    if (trimmed.includes(sep)) {
      const parts = trimmed.split(sep);
      let changed = false;
      const mappedParts = parts.map((p) => {
        const sub = lookupExtendedPhrase(p, loc, primaryLookup);
        if (sub && sub !== p.trim()) {
          changed = true;
          return p.replace(p.trim(), sub);
        }
        return p;
      });
      if (changed) {
        return mappedParts.join(sep);
      }
    }
  }

  // 6. Parameterized patterns like "Cortex-A76 (4 cores)" or "12 items"
  const coresMatch = trimmed.match(/^(.*?\(\d+)\s+cores(\).*)$/i);
  if (coresMatch) {
    return `${coresMatch[1]} ${CORES_WORDS[idx]}${coresMatch[2]}`;
  }
  const itemsMatch = trimmed.match(/^(\d+)\s+items$/i);
  if (itemsMatch) {
    return `${itemsMatch[1]} ${ITEMS_WORDS[idx]}`;
  }

  // 7. Word-boundary compositional phrase/term replacement for remaining English UI strings
  // Skip technical paths, URLs, and filenames
  if (
    trimmed.startsWith("/") ||
    trimmed.startsWith("http://") ||
    trimmed.startsWith("https://") ||
    trimmed.startsWith("mqtt://") ||
    trimmed.endsWith(".hef") ||
    trimmed.endsWith(".toml") ||
    trimmed.endsWith(".crt")
  ) {
    return undefined;
  }

  let composed = trimmed;
  let replacedAny = false;
  for (const [enTerm, row] of ALL_GLOSSARY_TERMS_22) {
    const escaped = enTerm.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const re = new RegExp(`\\b${escaped}\\b`, "gi");
    if (re.test(composed)) {
      const target = row[idx];
      composed = composed.replace(re, () => {
        replacedAny = true;
        return target;
      });
    }
  }

  if (replacedAny && composed !== trimmed) {
    return composed;
  }

  return undefined;
}
