// Build fast lookup tables per locale
const EXACT_MAP = new Map<string, Row22>();
function registerPhraseMap(dict: Record<string, Row22>) {
  for (const [en, row] of Object.entries(dict)) {
    const normEllipsis = en.replace(/\.{3}/g, "…");
    const normDots = en.replace(/…/g, "...");
    for (const variant of [en, normEllipsis, normDots]) {
      if (!EXACT_MAP.has(variant)) {
        EXACT_MAP.set(variant, row);
      }
      const lower = variant.toLowerCase();
      if (!EXACT_MAP.has(lower)) {
        EXACT_MAP.set(lower, row);
      }
    }
  }
}
